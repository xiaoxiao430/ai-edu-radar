def text_lines(value, width):
    """Wrap CJK text by approximate display width; never silently omit content."""
    lines, line, used = [], '', 0
    for char in str(value):
        size = 1 if ord(char) < 128 else 2
        if used + size > width and line:
            lines.append(line); line, used = '', 0
        line += char; used += size
    if line: lines.append(line)
    return lines or ['']

def svg_text(value, x, y, size=26, width=28, line_height=38, fill='#142d43', weight='400'):
    return ''.join(f'<text x="{x}" y="{y + i*line_height}" font-size="{size}" font-weight="{weight}" fill="{fill}">{html.escape(line)}</text>' for i,line in enumerate(text_lines(value,width)))

